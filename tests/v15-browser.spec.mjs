import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
test('V15: páginas con titulares independientes, formulario externo opcional y entrega ZIP',async({page},info)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/estudio/builder-v12.html?new=1');
 await expect(page.locator('#status')).toContainText('Listo:');
 await page.locator('#tab-sections').click();
 await page.locator('#v14-multipage').check();
 await expect(page.locator('#v15-page-editor')).toBeVisible();
 await page.locator('#v14-page-preview').selectOption('services');
 await page.locator('#v15-headline').fill('Servicios exclusivos V15');
 await expect(page.frameLocator('#live-preview').locator('h1')).toContainText('Servicios exclusivos V15');
 await page.locator('#v14-page-preview').selectOption('about');
 await page.locator('#v15-headline').fill('Historia única V15');
 await expect(page.frameLocator('#live-preview').locator('h1')).toContainText('Historia única V15');
 await page.locator('#v14-page-preview').selectOption('services');
 await expect(page.locator('#v15-headline')).toHaveValue('Servicios exclusivos V15');
 await page.locator('#v14-page-preview').selectOption('contact');
 await page.locator('#tab-brand').click();
 await page.locator('.advanced summary').click();
 await page.locator('#email').fill('ejemplo@dominio.es');
 await page.locator('#v15-form-mode').selectOption('formsubmit');
 await expect(page.locator('#email')).toHaveValue('ejemplo@dominio.es');
 await page.locator('#tab-sections').click();
 await page.locator('#v14-page-preview').selectOption('contact');
 await expect(page.frameLocator('#live-preview').locator('form[data-provider="formsubmit"]')).toHaveCount(1);
 await expect(page.frameLocator('#live-preview').locator('input[name="consentimiento"]')).toHaveCount(1);
 await info.attach('v15-editor-desktop',{body:await page.screenshot({fullPage:true}),contentType:'image/png'});
 await page.setViewportSize({width:390,height:844});
 await info.attach('v15-editor-mobile',{body:await page.screenshot({fullPage:true}),contentType:'image/png'});
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#export').click()]);
 const archive=await download.path();
 const list=execFileSync('unzip',['-Z','-1',archive],{encoding:'utf8'});
 for(const name of ['index.html','nosotros.html','servicios.html','galeria.html','contacto.html','PAGINAS-V15.json','ENTREGA-V15.txt'])expect(list).toContain(name);
 const services=execFileSync('unzip',['-p',archive,'servicios.html'],{encoding:'utf8'});
 const about=execFileSync('unzip',['-p',archive,'nosotros.html'],{encoding:'utf8'});
 const contact=execFileSync('unzip',['-p',archive,'contacto.html'],{encoding:'utf8'});
 expect(services).toContain('Servicios exclusivos V15');
 expect(services).not.toContain('Historia única V15');
 expect(about).toContain('Historia única V15');
 expect(contact).toContain('data-provider="formsubmit"');
 expect(contact).toContain('name="consentimiento"');
 expect(errors).toEqual([]);
});
test('V15: imagen del gestor exportada como archivo real sin aparecer en otras páginas',async({page})=>{
 await page.goto('/estudio/builder-v12.html?new=1');
 await expect(page.locator('#status')).toContainText('Listo:');
 await page.locator('#tab-sections').click();
 await page.locator('#v14-multipage').check();
 await page.locator('#v14-page-preview').selectOption('gallery');
 const source=await page.evaluate(()=>{
  const c=document.createElement('canvas');c.width=180;c.height=120;
  const ctx=c.getContext('2d');ctx.fillStyle='#267e91';ctx.fillRect(0,0,180,120);
  ctx.fillStyle='#f5a85c';ctx.fillRect(20,20,140,80);
  return c.toDataURL('image/png').split(',')[1];
 });
 await page.locator('#v15-photo-upload').setInputFiles({name:'ejemplo.png',mimeType:'image/png',buffer:Buffer.from(source,'base64')});
 await expect(page.locator('#v15-photo-library .v15-photo-card')).toHaveCount(1);
 await page.locator('#v15-photo-select').selectOption('photo-1');
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#export').click()]);
 const zip=await download.path(),names=execFileSync('unzip',['-Z','-1',zip],{encoding:'utf8'});
 expect(names).toContain('assets/v15-photo-photo-1.webp');
 const gallery=execFileSync('unzip',['-p',zip,'galeria.html'],{encoding:'utf8'});
 const about=execFileSync('unzip',['-p',zip,'nosotros.html'],{encoding:'utf8'});
 expect(gallery).toContain('assets/v15-photo-photo-1.webp');
 expect(about).not.toContain('assets/v15-photo-photo-1.webp');
});
